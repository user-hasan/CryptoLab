    public static string StepLabel(string label)
    {
        if (string.IsNullOrWhiteSpace(label)) return label;
        if (StepLabels.TryGetValue(label, out var translated)) return translated;
        if (label.StartsWith("shift ", StringComparison.Ordinal)) return "إزاحة " + label.Substring(6);
        if (label.StartsWith("zigzag index ", StringComparison.Ordinal)) return "مؤشر متعرج " + label.Substring(13);
        if (label.StartsWith("grid cell ", StringComparison.Ordinal)) return "خلية شبكة " + label.Substring(10);
        if (label.EndsWith("-bit public key", StringComparison.Ordinal)) return "مفتاح عام " + label.Substring(0, label.Length - 14) + " بت";
        if (label.EndsWith("-bit private key", StringComparison.Ordinal)) return "مفتاح خاص " + label.Substring(0, label.Length - 15) + " بت";
        if (label.EndsWith("-bit key", StringComparison.Ordinal)) return "مفتاح " + label.Substring(0, label.Length - 8) + " بت";
        return label;
    }

