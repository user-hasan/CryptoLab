    public static string ExplainResult(string algorithmId, CryptoOperation operation)
    {
        return operation switch
        {
            CryptoOperation.Hash => HashResults.TryGetValue(algorithmId, out var hash) ? hash : HashResults["md5"],
            CryptoOperation.Encrypt => EncryptResults.TryGetValue(algorithmId, out var encrypt) ? encrypt : EncryptResults["caesar"],
            _ => DecryptResults.TryGetValue(algorithmId, out var decrypt) ? decrypt : DecryptResults["caesar"]
        };
    }

